# -*- coding: utf-8 -*-
"""活动建议的预设与提示词组装（纯 Python，零 Qt 依赖）。

两条约束，改提示词时别删
    1. **不要臆测具体内容** —— 送出去的摘要里只有应用名和时长，没有任何
       窗口标题。不写死这条，模型很容易顺着「code.exe 待了 3 小时」编出
       「你在开发 XX 项目」这种没有数据支撑的结论，用户一看就知道是瞎猜。
    2. **证据必须是摘要里真实出现过的数字** —— 结构化之后，每条建议都要挂
       `evidence`。如果不钉死这条，模型会把编出来的数字填进「证据」栏，
       而「证据」恰恰是用户用来核对的地方 —— 那比没有证据更糟。

输出格式见 `engine.activity.advice.ADVICE_JSON_SPEC`（system prompt 与
提问里各放一份，双重保险）。
"""
from __future__ import annotations

from engine.ai.types import Preset
from engine.activity.advice import ADVICE_JSON_SPEC

ADVISOR_SYSTEM_PROMPT = (
    "你是时间管理与工作节奏顾问，帮用户看清时间去向、调整节奏。\n"
    "\n"
    "你会收到一份**本机统计的活动记录**：只有应用名、类别、停留时长和"
    "键盘敲击频率（仅是次数）。记录里**没有**窗口标题、没有输入内容、"
    "没有截图 —— 所以你不知道用户具体在写什么、看什么。\n"
    "\n"
    "务必遵守：\n"
    "1. 只依据给出的数据下判断。**不要臆测具体内容** —— 别说「你在开发某某"
    "项目」「你在查某某资料」这类没有数据支撑的话。\n"
    "2. **每条建议都要挂证据，且证据必须是上面数据里真实出现过的数字**。\n"
    "   不要自己换算、不要估算、不要编 —— 用户会拿证据去核对，编一个数字"
    "   比不给证据更糟。\n"
    "3. 最多 3 条建议，要具体可执行（例如「把 14:00–16:00 设成免打扰块」），"
    "不要给「要提高效率」这种空话。\n"
    "4. 如果数据显示连续工作很久（例如超过 90 分钟没有休息），"
    "把「安排休息」放在第一条。\n"
    "5. 语气平实，不评判、不说教 —— 用户是来调整节奏的，不是来挨批评的。\n"
    "6. 数据不足时输出空的 advices 数组 `[]`，不要硬编。\n"
    "7. **先给一段 summary，再给建议数组**。summary 是整体判断（今天的时间"
    "主要花在哪、节奏怎么样），它和单条建议**不是一回事**：不要把某条建议"
    "换个说法抄进 summary，也不要罗列数字（上面的指标已经有了）。"
    "summary 里的数字同样必须是摘要里真实出现过的。\n"
    "\n"
    f"{ADVICE_JSON_SPEC}"
)

#: 活动建议专用预设。**不放进 `engine.ai.prompt.BUILTIN_PRESETS`** ——
#: 那个列表是全局预设（用户在预设管理里能选），而这个预设脱离活动记录
#: 就毫无意义，塞进去只会让预设列表变乱。
ADVISOR_PRESET = Preset(
    id="activity_advisor",
    name="活动建议",
    system_prompt=ADVISOR_SYSTEM_PROMPT,
    default_delivery="panel",
    description="根据活动记录给出节奏建议与规划",
)


def build_advisor_prompt(summary: str, *, days: int = 7) -> str:
    """把本地摘要包成一次提问。

    开头显式写明「数据里有什么、没有什么」—— 与 system prompt 里的约束
    呼应，双重保险，降低模型自由发挥的空间。
    """
    return (
        f"以下是我最近 {days} 天由本机统计出的活动记录"
        "（只有应用名、类别、时长和敲击频率，没有任何窗口标题或输入内容）：\n"
        "\n"
        f"{summary}\n"
        "\n"
        "请据此给出最多 3 条节奏建议。**只依据上面的数据**，"
        "不要臆测我在做什么具体的事；每条建议都要挂上数据里**真实出现过**的数字"
        "作为证据，不要自己换算或估算。\n"
        "\n"
        "先写一段 summary（今天整体怎么样），再写建议数组。\n"
        "\n"
        "按下面格式**只输出 JSON**：\n"
        "\n"
        f"{ADVICE_JSON_SPEC}"
    )
